// Gzip dist/index.html and write it as a C header for the firmware.
// The symbol names (index_html_gz, index_html_gz_len) are what the web server
// code includes, keep them stable.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync, constants } from 'node:zlib';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const input = resolve(root, 'dist/index.html');
const output = resolve(root, '../esp32-legged-robot/web/index.html.gz.h');
// Fail the build if the page grows unexpectedly: it lives in flash.
const MAX_GZ_BYTES = 16 * 1024;

const html = readFileSync(input);
const gz = gzipSync(html, { level: constants.Z_BEST_COMPRESSION });

if (gz.length > MAX_GZ_BYTES) {
  console.error(`index.html.gz is ${gz.length} bytes, over the ${MAX_GZ_BYTES} byte budget`);
  process.exit(1);
}

const lines = [];
for (let i = 0; i < gz.length; i += 16) {
  lines.push('\t' + [...gz.subarray(i, i + 16)].map((b) => '0x' + b.toString(16).padStart(2, '0')).join(','));
}

const header = `// Generated by src/web (npm run build). Do not edit.
#pragma once
#define index_html_gz_len ${gz.length}
static const uint8_t index_html_gz[] PROGMEM = {
${lines.join(',\n')}
};
`;

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, header);
console.log(`index.html ${html.length} B -> gzip ${gz.length} B -> ${output}`);
